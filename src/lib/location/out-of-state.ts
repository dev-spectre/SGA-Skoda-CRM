const OUT_OF_STATE_ABBRS = new Set([
  'up', 'mp', 'ap', 'wb', 'kl', 'ka', 'mh', 'gj', 'rj', 'hr', 'pb', 'dl', 'ts', 'uk', 'hp', 'jk'
]);

/**
 * Checks whether a given location query or city name is outside Tamil Nadu.
 * Uses:
 * 1. 6-digit Pincode analysis (out-of-state pincodes)
 * 2. Local Tamil Nadu dictionary matching (never classifies known TN towns as outside)
 * 3. Pre-indexed out-of-state cities/states keywords
 * 4. In-memory LocationCache lookup with GPS bounding box + state validation
 */
export function isLocationOutsideTamilNadu(city: string | null | undefined): boolean {
  if (!city || !city.trim()) {
    // If no city is specified, the lead is not confirmed outside Tamil Nadu
    return false;
  }

  const query = city.trim();
  const lowerQuery = query.toLowerCase();

  // If query is a generic placeholder or junk value, keep as inside TN campaign
  if (/^(city|n\/?a|null|nil|none|test|yes|no|\.|\-)$/i.test(lowerQuery)) {
    return false;
  }
  if (lowerQuery.length <= 2 && !OUT_OF_STATE_ABBRS.has(lowerQuery)) {
    return false;
  }

  // 1. Check out-of-state postal code
  const pinCheck = extractPincode(query);
  if (pinCheck.isOutOfStatePincode) {
    return true;
  }

  // 2. Local Tamil Nadu dictionary check:
  // If matched locally inside TN dictionary, it is guaranteed to be in Tamil Nadu!
  const locMatch = resolveLocation(query);
  if (locMatch.isOutOfState) {
    return true;
  }
  if (locMatch.matched) {
    return false;
  }

  // Non-Tamil Indic script check:
  // Locations written in Malayalam (Kerala), Telugu (AP/TS), Kannada (Karnataka),
  // Gujarati, Odia, Gurmukhi (Punjab), Bengali, or Devanagari (Hindi) that didn't match TN dictionary
  if (/[\u0D00-\u0D7F\u0C00-\u0C7F\u0C80-\u0CFF\u0A80-\u0AFF\u0B00-\u0B7F\u0A00-\u0A7F\u0980-\u09FF\u0900-\u097F]/.test(query)) {
    return true;
  }

  // 3. Direct match against out-of-state keywords
  const normKey = normalizeKey(query);
  if (OUT_OF_STATE_KEYWORDS.has(normKey) || OUT_OF_STATE_KEYWORDS.has(lowerQuery)) {
    return true;
  }

  // Check state abbreviations (e.g. 'up', 'mp')
  if (OUT_OF_STATE_ABBRS.has(lowerQuery)) {
    return true;
  }

  // Check individual words in location string (e.g. "Edavanna Malappuram", "Bangalore North", "Thrissur Kerala")
  const tokens = lowerQuery.split(/[\s,./\\-_()]+/).filter((t) => t.length >= 2);
  for (const t of tokens) {
    const tNorm = normalizeKey(t);
    if (OUT_OF_STATE_KEYWORDS.has(t) || OUT_OF_STATE_KEYWORDS.has(tNorm) || OUT_OF_STATE_ABBRS.has(t)) {
      return true;
    }
  }

  // 4. In-memory LocationCache check (bounding rectangle and state check)
  const cached = getCachedLocationFromMemory(normKey) || getCachedLocationFromMemory(normalizeKey(lowerQuery));
  if (cached) {
    if (cached.state) {
      if (!isTamilNaduState(cached.state)) {
        return true;
      }
      return false;
    }
    if (typeof cached.latitude === 'number' && typeof cached.longitude === 'number' && (cached.latitude !== 0 || cached.longitude !== 0)) {
      const withinBounds = isWithinTamilNaduBounds(cached.latitude, cached.longitude);
      return !withinBounds;
    }
    if (cached.isTamilNadu !== undefined) {
      return !cached.isTamilNadu;
    }
  }

  // Default: if not confirmed outside, keep as inside Tamil Nadu
  return false;
}
